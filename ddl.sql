USE GaraDB;
GO

CREATE TABLE Customer (
  MaKH VARCHAR(10) PRIMARY KEY,
  TenKH NVARCHAR(100) NOT NULL,
  SDT VARCHAR(20) NULL,
  Email NVARCHAR(100) NULL,
  DiaChi NVARCHAR(200) NULL
);
GO

CREATE TABLE Vehicle (
  MaXe VARCHAR(12) PRIMARY KEY,
  BienSo NVARCHAR(20) NOT NULL UNIQUE,
  MaKH VARCHAR(10) NOT NULL,
  HangXe NVARCHAR(50) NULL,
  Model NVARCHAR(50) NULL,
  NamSX INT NULL,
  CONSTRAINT FK_Vehicle_Customer FOREIGN KEY (MaKH) REFERENCES Customer(MaKH)
);
GO

CREATE TABLE Mechanic (
  MaNV VARCHAR(10) PRIMARY KEY,
  TenNV NVARCHAR(100) NOT NULL,
  ChucVu NVARCHAR(50) NULL,
  SDT VARCHAR(20) NULL
);
GO

CREATE TABLE ServiceType (
  MaLoai VARCHAR(10) PRIMARY KEY,
  TenLoai NVARCHAR(100) NOT NULL,
  DonGia DECIMAL(18,2) NOT NULL CHECK (DonGia >= 0),
  MoTa NVARCHAR(200) NULL
);
GO

CREATE TABLE RepairOrder (
  MaDon VARCHAR(12) PRIMARY KEY,
  MaKH VARCHAR(10) NOT NULL,
  MaXe VARCHAR(12) NOT NULL,
  NgayTiepNhan DATE NOT NULL,
  NgayHoanThanh DATE NULL,
  TrangThai NVARCHAR(20) NOT NULL CHECK (TrangThai IN ('Received','InProgress','Completed','Cancelled')),
  GhiChu NVARCHAR(200) NULL,
  CONSTRAINT FK_RepairOrder_Customer FOREIGN KEY (MaKH) REFERENCES Customer(MaKH),
  CONSTRAINT FK_RepairOrder_Vehicle FOREIGN KEY (MaXe) REFERENCES Vehicle(MaXe),
  CONSTRAINT CK_RepairOrder_Date CHECK (NgayHoanThanh IS NULL OR NgayHoanThanh >= NgayTiepNhan)
);
GO

CREATE TABLE RepairDetail (
  MaDon VARCHAR(12) NOT NULL,
  STT INT NOT NULL,
  MaLoai VARCHAR(10) NOT NULL,
  DonGia DECIMAL(18,2) NOT NULL CHECK (DonGia >= 0),
  SoLuong INT NOT NULL CHECK (SoLuong > 0),
  PRIMARY KEY (MaDon, STT),
  CONSTRAINT FK_RepairDetail_RepairOrder FOREIGN KEY (MaDon) REFERENCES RepairOrder(MaDon),
  CONSTRAINT FK_RepairDetail_ServiceType FOREIGN KEY (MaLoai) REFERENCES ServiceType(MaLoai)
);
GO

CREATE TABLE SparePart (
  MaPT VARCHAR(10) PRIMARY KEY,
  TenPT NVARCHAR(100) NOT NULL,
  DonGia DECIMAL(18,2) NOT NULL CHECK (DonGia >= 0),
  SoLuongTon INT NOT NULL CHECK (SoLuongTon >= 0),
  NhaCungCap NVARCHAR(100) NULL
);
GO

CREATE TABLE Invoice (
  MaHD VARCHAR(12) PRIMARY KEY,
  MaDon VARCHAR(12) NOT NULL UNIQUE,
  MaNV VARCHAR(10) NOT NULL,
  NgayLap DATE NOT NULL,
  TriGia DECIMAL(18,2) NOT NULL CHECK (TriGia >= 0),
  DaThanhToan BIT DEFAULT 0,
  CONSTRAINT FK_Invoice_RepairOrder FOREIGN KEY (MaDon) REFERENCES RepairOrder(MaDon),
  CONSTRAINT FK_Invoice_Mechanic FOREIGN KEY (MaNV) REFERENCES Mechanic(MaNV)
);
GO